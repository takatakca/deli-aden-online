const DICT: Record<Lang, Table> = { fr: FR as unknown as Table, en: EN, es: ES };

const KEY = "deliaden_lang";
// Stays "fr" during SSR *and* first client render — hydration-safe.
let current: Lang = "fr";
let hydrated = false;
const listeners = new Set<() => void>();

export const i18n = {
  get lang(): Lang {
    return current;
  },
  set(lang: Lang) {
    current = lang;
    if (typeof window !== "undefined") window.localStorage.setItem(KEY, lang);
    if (typeof document !== "undefined") document.documentElement.lang = lang;
    listeners.forEach((l) => l());
  },
  /** Applies the persisted language after hydration. Safe to call repeatedly. */
  hydrate() {
    if (hydrated || typeof window === "undefined") return;
    hydrated = true;
    const saved = window.localStorage.getItem(KEY) as Lang | null;
    if (saved && saved !== current && LANGS.some((l) => l.code === saved)) i18n.set(saved);
  },
  subscribe(l: () => void) {
    listeners.add(l);
    return () => listeners.delete(l);
  },
  t(key: TKey, lang: Lang = current): string {
    return DICT[lang][key] ?? (FR as unknown as Table)[key] ?? key;
  },
  format(key: TKey, vars: Record<string, string | number>, lang: Lang = current): string {
    return Object.entries(vars).reduce(
      (out, [k, v]) => out.replace(new RegExp(`\\{${k}\\}`, "g"), String(v)),
      i18n.t(key, lang),
    );
  },
  speechLocale(lang: Lang = current) {
    return LANGS.find((l) => l.code === lang)?.speech ?? "fr-CA";
  },
};

export function useLang(): Lang {
  const lang = useSyncExternalStore(
    i18n.subscribe,
    () => current,
    () => "fr" as Lang,
  );
  useEffect(() => i18n.hydrate(), []);
  return lang;
}

export function useT() {
  const lang = useLang();
  return {
    lang,
    t: (key: TKey) => i18n.t(key, lang),
    tf: (key: TKey, vars: Record<string, string | number>) => i18n.format(key, vars, lang),
  };
}
